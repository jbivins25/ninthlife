#!/usr/bin/env python3

from PIL import Image
import numpy as np
import argparse
import os
import sys

parser = argparse.ArgumentParser(description="Process filenames and flags")

parser.add_argument(
	"filenames",
	nargs="+",
	help="One or more .png filenames"
)

parser.add_argument(
	"-r", "-rows",
	type=int,
	default=40,
	help="Number of rows for the output array"
)

parser.add_argument(
	"-c", "-columns",
	type=int,
	default=36,
	help="Number of columns for the output array"
)

parser.add_argument(
	"-o", "-output",
	type=str,
	default="",
	help="Output directory"
)

argv = parser.parse_args()

collision_map = np.zeros((argv.r,argv.c))

for filename in argv.filenames:
	if not ".png" in filename:
		continue
	try:
		with Image.open(filename) as file:
			pixels = file.load()

			width, height = file.size
			for y in range(0, height, 4):
				for x in range(0, width, 4):
					r, _, _, a = pixels[x,y]
					if a < 255:
						continue
					if x / 4 >= argv.r or y / 4 >= argv.c:
						continue
					collision_map[int(x/4)][int(y/4)] = int(round(r/16))
					
	except FileNotFoundError:
		print(f"Could not find file {filename}")
		continue

	path = os.path.join(os.getcwd(), argv.o)

	temp = filename.split('\\')[-1]
	temp = temp.split('/')[-1]
	output_file = temp.removesuffix(".png")
	path = os.path.join(path, output_file+'.h')
	with open(path, "w") as file:
		file.write(f"//Auto-generated by collision_converter.py\n\n#ifndef {output_file.upper()+'_H'}\n#define {output_file.upper()+'_H'}\n\n")
		file.write("#include <gb/gb.h>\n\n")
		file.write(f"const uint8_t {output_file+'_WIDTH'} = {argv.r};\n")
		file.write(f"const uint8_t {output_file+'_HEIGHT'} = {argv.c};\n\n")
		file.write(f"const uint8_t {output_file+'_map'}[{argv.r}][{argv.c}] = {{\n")
		for x in range(argv.r):
			file.write("\t{ ")
			for y in range(argv.c):
				file.write(f"{int(collision_map[x][y])}")
				if y+1 < argv.c:
					file.write(", ")
			if x+1 < argv.r:
				file.write(" },\n")
			else:
				file.write(" }\n")
		file.write("};\n\n")
		file.write("#endif\n")

w, h = collision_map.shape

image_data = np.zeros((w,h,4), dtype=np.uint8)

for x in range(w):
	for y in range(h):
		r = g = b = int((collision_map[x][y]/256)*255)
		if r == 0:
			a = 0
		else:
			a = 255
		image_data[x,y] = [r,g,b,a]

image = Image.fromarray(image_data)
image.save("test_cm.png")
